import { NextRequest, NextResponse } from 'next/server';
import prisma from '@/lib/db';
import { requireUserId } from '@/lib/auth';

const YTMUSIC_SERVICE_URL = process.env.YTMUSIC_SERVICE_URL || 'http://localhost:8000';

export async function POST(request: NextRequest) {
  try {
    const { playlistId } = await request.json();
    const userId = await requireUserId();

    if (!userId) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }
    if (!playlistId) {
      return NextResponse.json({ error: 'Missing playlistId' }, { status: 400 });
    }

    // 1. Get the playlist from the database
    const playlist = await prisma.playlist.findFirst({
      where: { id: playlistId, userId },
    });

    if (!playlist) {
      return NextResponse.json({ error: 'Playlist not found' }, { status: 404 });
    }

    const tracks = JSON.parse(playlist.tracks);
    const videoIds: string[] = [];

    // 2. Fetch video IDs from ytmusic-service for each track
    // (In a production system, this should be done with concurrency limit or batched)
    for (const track of tracks) {
      try {
        const query = `${track.name} ${track.artist}`;
        const searchRes = await fetch(`${YTMUSIC_SERVICE_URL}/search`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ query }),
        });

        if (searchRes.ok) {
          const searchData = await searchRes.json();
          if (searchData.results && searchData.results.length > 0) {
            videoIds.push(searchData.results[0].videoId);
          }
        }
      } catch (err) {
        console.error(`Failed to find video ID for track: ${track.name}`, err);
      }
    }

    if (videoIds.length === 0) {
      return NextResponse.json({ error: 'Could not find any matching tracks on YouTube Music' }, { status: 400 });
    }

    // 3. Create the playlist on YT Music via the service
    const createRes = await fetch(`${YTMUSIC_SERVICE_URL}/playlist`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        title: playlist.name,
        description: playlist.description || 'Generated by MusiBrain AI',
        video_ids: videoIds,
      }),
    });

    if (!createRes.ok) {
      const errorData = await createRes.json();
      return NextResponse.json({ error: errorData.detail || 'Failed to create playlist on YT Music' }, { status: createRes.status });
    }

    const createData = await createRes.json();

    // 4. Update the playlist in the DB with the ytMusicId
    await prisma.playlist.update({
      where: { id: playlist.id },
      data: { ytMusicId: createData.playlist_id },
    });

    return NextResponse.json({
      success: true,
      playlistUrl: createData.url,
      ytMusicId: createData.playlist_id,
    });

  } catch (error) {
    console.error('YTMusic Export error:', error);
    return NextResponse.json(
      { error: 'Failed to export playlist to YouTube Music' },
      { status: 500 }
    );
  }
}
